// ============================================================
// [RestaurantForm.java] 맛집 등록/수정 요청 데이터 전달 객체 (DTO)
// ============================================================
// 역할: 사용자가 맛집 등록/수정 화면에서 입력한 정보를 담는 "택배 상자"
//       가게 이름, 카테고리, 주소, 전화번호, 설명 등을 서버로 전달합니다.
//
// DTO(Data Transfer Object)란?
//   비유: 택배 상자 — 데이터를 한 곳에서 다른 곳으로 안전하게 운반하는 용도
//   웹 브라우저(프론트엔드) → 서버(백엔드)로 데이터를 전달할 때 사용합니다.
//
// DTO vs Entity 차이:
//   Entity = DB 테이블과 직접 매핑되는 핵심 객체 (@Setter 금지, 불변 설계)
//            비유: 금고 속 원본 서류 — 함부로 수정하면 안 됨
//   DTO    = 데이터를 운반만 하는 일회용 상자 (@Setter 허용, 자유롭게 값 변경)
//            비유: 복사한 서류를 담는 서류봉투 — 자유롭게 사용 가능
//
// 사용 흐름:
//   1) 사용자가 맛집 등록 폼에 가게 이름/카테고리/주소/전화번호/설명 입력
//   2) JavaScript의 fetch()가 JSON으로 서버에 전송
//      예: { "name": "홍콩반점", "category": "CHINESE", "address": "서울시 강남구", ... }
//   3) Spring이 JSON을 RestaurantForm 객체로 자동 변환 (@RequestBody)
//   4) @Valid로 검증 → 통과하면 RestaurantService.register()에 전달
//   5) RestaurantService에서 Restaurant 엔티티로 변환 후 DB에 저장
//
// 검증(Validation) 어노테이션 정리:
//   - @NotBlank : 빈 문자열("") 또는 공백만 있는 문자열("  ") 거부 (문자열 전용)
//   - @NotNull  : null 값만 거부 (모든 타입에 사용 가능, enum/숫자에 적합)
//   - @Size     : 문자열의 최소/최대 길이 검증
// ============================================================

// --- 패키지 선언 ---
// 이 파일이 속한 폴더(패키지) 경로를 지정합니다.
// com.example.mymatzip.dto = "DTO(데이터 전달 객체)" 계층에 해당
package com.example.mymatzip.dto;

// --- import 영역 (외부 클래스 가져오기) ---

// Category 열거형(enum) 가져오기 — 맛집의 음식 종류를 정의한 enum
// KOREAN(한식), CHINESE(중식), JAPANESE(일식) 등의 값이 정의되어 있음
// 이 DTO의 category 필드 타입으로 사용됩니다.
import com.example.mymatzip.entity.Category;

// @NotBlank 어노테이션 가져오기 — 값이 비어있지 않은지 검증 (문자열 전용)
// null, 빈 문자열(""), 공백만 있는 문자열("  ") 모두 거부합니다.
import jakarta.validation.constraints.NotBlank;

// @NotNull 어노테이션 가져오기 — null 값만 거부하는 검증 어노테이션
// @NotBlank는 String에만 사용 가능하지만, @NotNull은 모든 타입에 사용 가능
// Category(enum) 같은 비문자열 타입에는 @NotNull을 사용합니다.
import jakarta.validation.constraints.NotNull;

// @Size 어노테이션 가져오기 — 문자열의 최소/최대 길이를 검증하는 어노테이션
// 예: @Size(max = 50) → 50글자 이하만 허용
import jakarta.validation.constraints.Size;

// @Getter 가져오기 — Lombok이 모든 필드의 getter 메서드를 자동 생성
// 예: getName(), getCategory(), getAddress(), getPhone(), getDescription()
import lombok.Getter;

// @Setter 가져오기 — Lombok이 모든 필드의 setter 메서드를 자동 생성
// 예: setName(), setCategory(), setAddress(), setPhone(), setDescription()
// Spring이 JSON → 객체 변환 시 setter를 사용하므로 DTO에는 필수입니다.
import lombok.Setter;

// @Getter 어노테이션 — 모든 필드에 대해 getter 메서드를 자동 생성
// 이 어노테이션이 있으면 getName(), getCategory() 등의 메서드가 자동으로 만들어집니다.
@Getter

// @Setter 어노테이션 — 모든 필드에 대해 setter 메서드를 자동 생성
// 이 어노테이션이 있으면 setName(), setCategory() 등의 메서드가 자동으로 만들어집니다.
@Setter

// RestaurantForm 클래스 선언
// DTO(Data Transfer Object) = 맛집 등록/수정 데이터를 전달하기 위한 "택배 상자" 역할의 클래스
public class RestaurantForm {

    // ──────────────────────────────────────────────────────
    // 맛집 이름 필드
    // ──────────────────────────────────────────────────────
    // [타입] String — 문자열 (예: "홍콩반점", "스시오마카세")
    // [용도] 사용자가 등록 폼에 입력한 맛집 이름을 저장
    // [DB 매핑] → Restaurant 엔티티의 name 필드로 전달되어 DB에 저장됨
    //
    // @NotBlank: 빈 값 검증 → null, "", "  " 모두 거부
    //   → 검증 실패 시 "맛집 이름을 입력해주세요." 메시지 반환
    // @Size(max=50): 최대 길이 검증 → 50자 이하만 허용
    //   → DB 컬럼 크기 제한에 맞추기 위한 검증
    //   → 검증 실패 시 "맛집 이름은 50자 이내로 입력해주세요." 메시지 반환
    // ──────────────────────────────────────────────────────
    @NotBlank(message = "맛집 이름을 입력해주세요.")                         // 빈 값 검증 — 비어있으면 에러
    @Size(max = 50, message = "맛집 이름은 50자 이내로 입력해주세요.")        // 길이 검증 — 최대 50자
    private String name;                                                   // 맛집 이름 (예: "홍콩반점")

    // ──────────────────────────────────────────────────────
    // 카테고리 필드 (음식 종류)
    // ──────────────────────────────────────────────────────
    // [타입] Category — 열거형(enum) (예: Category.KOREAN, Category.CHINESE)
    //   Category enum에 정의된 값: KOREAN(한식), CHINESE(중식), JAPANESE(일식) 등
    // [용도] 사용자가 드롭다운(선택 상자)에서 선택한 음식 카테고리를 저장
    // [DB 매핑] → Restaurant 엔티티의 category 필드로 전달되어 DB에 저장됨
    //
    // @NotNull: null 검증 → 카테고리를 선택하지 않으면 거부
    //   ★ @NotBlank 대신 @NotNull을 사용하는 이유:
    //     @NotBlank는 String(문자열) 전용이고, Category는 enum(열거형)이므로
    //     @NotNull을 사용해야 합니다.
    //   → 검증 실패 시 "카테고리를 선택해주세요." 메시지 반환
    // ──────────────────────────────────────────────────────
    @NotNull(message = "카테고리를 선택해주세요.")       // null 검증 — 선택하지 않으면 에러 (enum이므로 @NotNull 사용)
    private Category category;                         // 음식 카테고리 (예: Category.KOREAN = 한식)

    // ──────────────────────────────────────────────────────
    // 주소 필드
    // ──────────────────────────────────────────────────────
    // [타입] String — 문자열 (예: "서울시 강남구 역삼동 123-45")
    // [용도] 사용자가 등록 폼에 입력한 맛집 주소를 저장
    // [DB 매핑] → Restaurant 엔티티의 address 필드로 전달되어 DB에 저장됨
    //
    // @NotBlank: 빈 값 검증 → null, "", "  " 모두 거부
    //   → 검증 실패 시 "주소를 입력해주세요." 메시지 반환
    // ──────────────────────────────────────────────────────
    @NotBlank(message = "주소를 입력해주세요.")         // 빈 값 검증 — 비어있으면 에러
    private String address;                            // 맛집 주소 (예: "서울시 강남구 역삼동 123-45")

    // ──────────────────────────────────────────────────────
    // 전화번호 필드 (선택 입력)
    // ──────────────────────────────────────────────────────
    // [타입] String — 문자열 (예: "02-1234-5678")
    // [용도] 사용자가 등록 폼에 입력한 맛집 전화번호를 저장
    // [DB 매핑] → Restaurant 엔티티의 phone 필드로 전달되어 DB에 저장됨
    //
    // ★ 검증 어노테이션이 없는 이유:
    //   전화번호는 선택 입력(optional) 항목이므로 입력하지 않아도 됩니다.
    //   입력하지 않으면 null이 저장됩니다.
    // ──────────────────────────────────────────────────────
    private String phone;                              // 맛집 전화번호 (선택 입력, 예: "02-1234-5678")

    // ──────────────────────────────────────────────────────
    // 설명 필드 (선택 입력)
    // ──────────────────────────────────────────────────────
    // [타입] String — 문자열 (예: "점심 특선이 맛있는 중국집입니다.")
    // [용도] 사용자가 등록 폼에 입력한 맛집 설명/소개를 저장
    // [DB 매핑] → Restaurant 엔티티의 description 필드로 전달되어 DB에 저장됨
    //
    // @Size(max=500): 최대 길이 검증 → 500자 이하만 허용
    //   → 너무 긴 설명을 방지하기 위한 제한
    //   → 검증 실패 시 "설명은 500자 이내로 입력해주세요." 메시지 반환
    //
    // ★ @NotBlank가 없는 이유:
    //   설명은 선택 입력(optional) 항목이므로 입력하지 않아도 됩니다.
    //   다만, 입력할 경우 500자를 초과할 수 없습니다.
    // ──────────────────────────────────────────────────────
    @Size(max = 500, message = "설명은 500자 이내로 입력해주세요.")   // 길이 검증 — 최대 500자 (입력 시에만 적용)
    private String description;                                     // 맛집 설명 (선택 입력, 예: "점심 특선이 맛있는 중국집")

    // ──────────────────────────────────────────────────────
    // [Phase 7] 맛집 대표 이미지 URL 필드 (선택 입력)
    // ──────────────────────────────────────────────────────
    // [타입] String — 문자열 (예: "/uploads/a1b2c3d4-...-e5f6.jpg") 또는 null
    // [용도] 사용자가 이미지를 업로드한 후 반환된 URL을 저장
    //   → 이미지 업로드 API(POST /api/files/upload)를 먼저 호출하여 URL을 받고,
    //     해당 URL을 이 필드에 담아서 맛집 등록/수정 요청에 포함시킵니다.
    // [DB 매핑] → Restaurant 엔티티의 imageUrl 필드로 전달되어 DB에 저장됨
    //
    // ★ 검증 어노테이션이 없는 이유:
    //   이미지는 선택 입력(optional) 항목이므로 첨부하지 않아도 됩니다.
    // ──────────────────────────────────────────────────────
    private String imageUrl;                                        // 맛집 대표 이미지 URL (선택 입력)
}
