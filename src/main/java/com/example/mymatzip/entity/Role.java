package com.example.mymatzip.entity; // 이 파일이 속한 패키지(폴더) 선언
// 패키지란? 자바 파일들을 폴더별로 정리하는 방법입니다.
// com.example.mymatzip.entity = "com/example/mymatzip/entity" 폴더 안에 있다는 뜻
// entity 패키지에는 DB 테이블과 매핑되는 클래스들이 모여 있습니다.

// ============================================================
// [Role.java] 회원 역할 열거형 (Enum)
// ============================================================
//
// 역할: 회원의 권한 등급을 정의합니다.
//       USER(일반 사용자)와 ADMIN(관리자) 두 가지만 존재합니다.
//
// 비유: 놀이공원의 "입장권 종류" -- 일반권(USER)과 VIP권(ADMIN)
//       VIP권은 일반 구역 + VIP 라운지(관리 기능)까지 이용 가능
//       일반권은 일반 구역(본인 글 관리)만 이용 가능
//
// 왜 enum(열거형)을 사용하나요?
//   - 역할은 USER와 ADMIN 두 가지뿐이므로, 만약 String(문자열)으로 저장하면
//     "user", "User", "USER", "관리자" 등 사람마다 다르게 입력할 수 있습니다.
//   - enum은 미리 정해진 값만 허용하므로 오타를 컴파일(코드 변환) 시점에 잡아줍니다.
//   - 비유: 시험 답안지에서 "주관식"(String) 대신 "객관식"(enum)을 쓰는 것!
//     객관식은 1번, 2번, 3번 중에서만 고를 수 있으니 엉뚱한 답이 나올 수 없습니다.
//
// DB 저장 방식:
//   Member 엔티티에서 @Enumerated(EnumType.STRING)을 사용하기 때문에
//   DB에는 "USER", "ADMIN" 문자열로 저장됩니다.
//   만약 EnumType.ORDINAL을 쓰면 0, 1 같은 숫자로 저장되는데,
//   나중에 enum 순서가 바뀌면 데이터가 꼬이므로 STRING을 사용합니다!
//
// 이 enum이 사용되는 곳들:
//   1. Member 엔티티의 role 필드 -- 회원이 어떤 역할인지 저장
//   2. MemberService -- 회원가입 시 기본 역할을 USER로 설정
//   3. RestaurantService -- 맛집 수정·삭제 시 ADMIN인지 확인 (ADMIN은 모든 맛집 수정·삭제 가능)
//   4. JSP 화면 -- 관리자에게만 "삭제" 버튼 표시
//   5. SecurityConfig -- /admin/** 주소는 ADMIN 권한만 접근 가능
// ============================================================

// public: 다른 파일(클래스)에서도 이 enum을 사용할 수 있도록 공개합니다.
//   비유: 도서관의 "공개 서가" -- 누구나 열람 가능
// enum: "열거형"이라는 특별한 자바 타입입니다. class(클래스)와 비슷하지만,
//   미리 정해진 상수 값들만 가질 수 있습니다.
// Role: 이 enum의 이름. "역할"이라는 뜻입니다.
public enum Role {

    // ──────────────────────────────────────────────────────────
    // enum 상수 정의 영역
    // 여기에 나열된 값들만 Role 타입으로 사용할 수 있습니다.
    // 비유: 혈액형이 A, B, O, AB만 있는 것처럼, Role은 USER와 ADMIN만 있습니다.
    // ──────────────────────────────────────────────────────────

    USER("일반 사용자"),   // 첫 번째 역할: 일반 사용자
    // "일반 사용자"는 displayName 필드에 저장되는 한글 이름입니다.
    // DB에는 영어 "USER"로 저장되고, 화면에서는 "일반 사용자"로 보여줍니다.
    // 비유: 영어 이름(USER)과 한글 이름(일반 사용자)을 함께 가진 명찰
    // [권한] 맛집 등록, 리뷰 작성, 찜하기, 본인이 쓴 글만 수정/삭제 가능

    ADMIN("관리자");       // 두 번째 역할: 관리자
    // "관리자"는 displayName 필드에 저장되는 한글 이름입니다.
    // DB에는 영어 "ADMIN"으로 저장되고, 화면에서는 "관리자"로 보여줍니다.
    // [권한] 일반 사용자의 모든 권한 + 다른 사람의 맛집/리뷰도 삭제 가능
    // 세미콜론(;)으로 enum 상수 목록의 끝을 표시합니다.

    // ──────────────────────────────────────────────────────────
    // 필드(변수) 영역
    // ──────────────────────────────────────────────────────────

    // private: 이 클래스 안에서만 직접 접근 가능 (외부에서는 getDisplayName()으로 접근)
    //   비유: 금고 안에 넣어둔 것 -- 열쇠(getter 메서드)가 있어야 꺼낼 수 있음
    // final: 한 번 값이 정해지면 절대 변경할 수 없음
    //   비유: 볼펜으로 쓴 글씨 -- 지울 수 없음. USER는 영원히 "일반 사용자"
    // String: 문자열 타입 -- 글자(텍스트)를 저장하는 자바 기본 타입
    // displayName: 변수 이름. "표시 이름"이라는 뜻으로, 화면에 보여줄 한글 이름
    private final String displayName;

    // ──────────────────────────────────────────────────────────
    // 생성자(Constructor) 영역
    // ──────────────────────────────────────────────────────────

    // enum 생성자 -- 각 enum 상수(USER, ADMIN)가 만들어질 때 자동으로 호출됩니다.
    // 비유: 공장에서 제품(enum 상수)을 찍어낼 때, 이름표(displayName)를 붙이는 과정
    //
    // 왜 public이 아닌가?
    //   enum의 생성자는 기본적으로 private입니다 (public 불가).
    //   이유: enum 상수는 위에서 선언한 것(USER, ADMIN)만 존재해야 하므로,
    //   외부에서 new Role("슈퍼관리자") 같은 식으로 새로 만들 수 없게 막아놓은 것입니다.
    //
    // 매개변수(Parameter):
    //   String displayName -- 화면에 표시할 한글 이름
    //   예: USER("일반 사용자") 호출 시 → displayName = "일반 사용자"
    //   예: ADMIN("관리자") 호출 시 → displayName = "관리자"
    Role(String displayName) {
        this.displayName = displayName;
        // this.displayName: 이 enum 상수의 displayName 필드 (위에서 선언한 변수)
        // displayName: 매개변수로 전달받은 값
        // this를 붙이는 이유: 필드 이름과 매개변수 이름이 같을 때, 구분하기 위해서
        //   this.displayName = "이 객체의 필드", displayName = "전달받은 값"
        // 비유: "내 이름(this.displayName)을 전달받은 이름(displayName)으로 설정해라"
    }

    // ──────────────────────────────────────────────────────────
    // 메서드(Method) 영역
    // ──────────────────────────────────────────────────────────

    // 한글 이름을 가져오는 메서드 (Getter 메서드)
    //
    // public: 어디서든 이 메서드를 호출할 수 있음 (공개 메서드)
    // String: 이 메서드가 돌려주는(반환하는) 값의 타입 -- 문자열
    // getDisplayName: 메서드 이름. "표시 이름을 가져오다"라는 뜻
    //   자바 관례: getter 메서드는 "get + 필드명"으로 이름을 짓습니다.
    // (): 매개변수 없음 -- 아무것도 전달받지 않고, 저장된 값만 돌려줌
    //
    // 사용 예시 (자바 코드에서):
    //   Role.USER.getDisplayName()  → "일반 사용자" 반환
    //   Role.ADMIN.getDisplayName() → "관리자" 반환
    //
    // 사용 예시 (JSP 화면에서):
    //   ${member.role.displayName}  → "일반 사용자" 또는 "관리자" 출력
    //   JSP에서는 get을 빼고 소문자로 시작하는 필드명으로 접근합니다.
    //
    // 반환값: displayName 필드에 저장된 한글 이름 문자열
    public String getDisplayName() {
        return displayName;
        // return: 메서드를 호출한 곳으로 값을 돌려보냄
        // displayName: 이 enum 상수가 가지고 있는 한글 이름
        // 비유: "내 한글 이름이 뭐냐고 물어보면, 이름표에 적힌 글씨를 보여주는 것"
    }
}
